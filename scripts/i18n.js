function configuredLanguage() {
  const direct = globalThis.game?.i18n?.lang;
  if (direct) return String(direct);
  try {
    const setting = globalThis.game?.settings?.get?.("core", "language");
    if (setting) return String(setting);
  } catch { /* Foundry settings are not available in isolated tests or early bootstrap. */ }
  return "";
}

function languageCode() {
  const raw = configuredLanguage().toLowerCase();
  return raw ? (raw.split(/[-_]/)[0] || "en") : "en";
}

function catalogValue(key) {
  const lang = languageCode();
  return CATALOGS[lang]?.[key] ?? CATALOGS.en?.[key] ?? null;
}

export function localize(key, fallback = key) {
  if (!key) return String(fallback ?? "");
  const own = String(key).startsWith("PF2E_CREATURE_FORGE.");
  // If Foundry exposes an active language, package-owned strings are resolved from
  // the embedded catalog first. This protects the UI from a missing/stale manifest
  // localization load while still following the user's current language.
  if (own && configuredLanguage()) {
    const embedded = catalogValue(key);
    if (embedded != null) return String(embedded);
  }
  const value = globalThis.game?.i18n?.localize?.(key);
  if (value && value !== key) return String(value);
  const embedded = catalogValue(key);
  return embedded != null ? String(embedded) : String(fallback ?? key);
}

export function format(key, data = {}, fallback = key) {
  const own = String(key ?? "").startsWith("PF2E_CREATURE_FORGE.");
  let template = own && configuredLanguage() ? catalogValue(key) : null;
  if (template == null) {
    const value = globalThis.game?.i18n?.format?.(key, data);
    if (value && value !== key) return String(value);
    template = catalogValue(key) ?? fallback ?? key;
  }
  return String(template).replace(/\{([^}]+)\}/g, (_match, name) => data?.[name] ?? `{${name}}`);
}

export function currentLanguage() {
  return languageCode();
}

export function hasEmbeddedTranslation(key, lang = languageCode()) {
  const code = String(lang ?? "en").toLowerCase().split(/[-_]/)[0];
  return Object.prototype.hasOwnProperty.call(CATALOGS[code] ?? {}, key);
}
